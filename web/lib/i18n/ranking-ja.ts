export function rankingDynamicJapanese(text: string): string | null {
  const rank = /^(\d+)위(.*)$/.exec(text);
  if (rank) {
    const retry = /^ 영상 가져오는 중 · (\d+\/\d+)회$/.exec(rank[2]);
    if (retry) return `${rank[1]}位の動画を読み込み中 ・ ${retry[1]}回`;
    if (rank[2].startsWith(": ")) {
      const cause = rank[2].slice(2);
      return `${rank[1]}位：${rankingJapanese[cause] ?? cause}`;
    }
    return rankActions[rank[2]]?.(rank[1]) ?? null;
  }
  const save = /^저장하고 (\d+)위로 →$/.exec(text);
  if (save) return `保存して${save[1]}位へ →`;
  const count = /^(\d+)개 표시$/.exec(text);
  if (count) return `${count[1]}件表示`;
  const range = /^([\d:.]+\s*–\s*[\d:.]+) · 구간 수정$/.exec(text);
  if (range) return `${range[1]} ・ 区間を変更`;
  const control = /^(.+) (더 보기|직접 선택|선택|템플릿)$/.exec(text);
  if (!control) return null;
  const label = rankingJapanese[control[1]] ?? control[1];
  if (/[가-힣]/.test(label)) return null;
  switch (control[2]) {
    case "더 보기": return `${label}をさらに表示`;
    case "직접 선택": return `${label}を指定`;
    case "선택": return `${label}を選択`;
    default: return `${label}のテンプレート`;
  }
}
