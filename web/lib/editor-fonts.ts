const stableEditorFontIdSet: ReadonlySet<EditorFontId> = new Set(
  stableEditorFontIds,
);

export const stableEditorFontOptions = stableEditorFontIds.map((fontId) => {
  const option = editorFontOptions.find((font) => font.id === fontId);
  if (!option) throw new Error(`Stable editor font is not bundled: ${fontId}`);
  return option;
});

export function isStableEditorFontId(
  value: unknown,
): value is StableEditorFontId {
  return typeof value === "string"
    && stableEditorFontIdSet.has(value as EditorFontId);
}

