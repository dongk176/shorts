export function monetizationTranslator(locale: SiteLocale) {
  return (
    key: keyof typeof monetizationMessages,
    values: Record<string, string | number> = {},
  ) => {
    const message: string =
      locale === "ko" ? key : monetizationMessages[key][locale];
    return message.replace(/\{(\w+)\}/g, (match, name: string) =>
      String(values[name] ?? match),
    );
  };
}
